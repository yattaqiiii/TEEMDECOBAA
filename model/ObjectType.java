package model;

// enum objecttype mendefinisikan jenis-jenis objek yang bisa muncul dalam game, seperti ayam, bom, kapas (cotton), dan semangka.
// setiap jenis objek ini bisa memiliki skor atau perilaku yang berbeda ketika berinteraksi dengan pemain.
public enum ObjectType {
    AYAM,
    BOM,
    COTTON,
    SEMANGKA
}